import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const cell=value=>String(value??'-').replaceAll('|','/').replace(/\r?\n/g,' ');
for(const [run,title,filename] of [['source-macos','Source regression matrix','SOURCE-MATRIX.md'],['lifecycle-macos','Framework and package-manager lifecycle matrix','LIFECYCLE-MATRIX.md']]) {
  const dir=path.join(here,'evidence',run);
  const manifest=JSON.parse(fs.readFileSync(path.join(dir,'manifest.json')));
  if(run==='lifecycle-macos'&&!manifest.completedAt) throw new Error('Lifecycle run has not completed');
  const rows=fs.readFileSync(path.join(dir,'results.jsonl'),'utf8').trim().split('\n').map(JSON.parse);
  const counts=Object.fromEntries(['PASS','FAIL','NOT TESTED','INFO'].map(s=>[s,rows.filter(r=>r.status===s).length]));
  const executed=counts.PASS+counts.FAIL, planned=executed+counts['NOT TESTED'];
  const lines=[`# ${title}`, '', 'Generated by `render-matrices.mjs`; raw rows and run identity are the source of truth.', '',
    `- Run manifest: [manifest.json](evidence/${run}/manifest.json).`,
    `- Raw results: [results.jsonl](evidence/${run}/results.jsonl).`,
    `- Source SHA: \`${manifest.sourceSha??manifest.auditedCliSha}\`.`,
    `- Platform: ${manifest.platform??manifest.os}; Node ${manifest.node}.`,
    `- PASS ${counts.PASS}; FAIL ${counts.FAIL}; NOT TESTED ${counts['NOT TESTED']}; INFO ${counts.INFO}.`,
    `- Coverage of this run's planned counted rows: ${executed}/${planned} (${(100*executed/planned).toFixed(1)}%).`,
    `- Pass rate among executed rows: ${counts.PASS}/${executed} (${(100*counts.PASS/executed).toFixed(1)}%).`, '',
    'These percentages apply only to this run. Commands, assertions, jobs and framework combinations use different counting units and must not be added together.', '',
    '| Case | Expected | Status | Exit | Command | Working directory | Evidence / observed |', '|---|---|---|---|---|---|---|'];
  for(const r of rows) {
    const command=Array.isArray(r.command)?r.command.map(a=>JSON.stringify(a)).join(' '):r.command;
    const links=r.stdout?`[stdout](evidence/${run}/${r.stdout.replaceAll('\\','/')}) [stderr](evidence/${run}/${r.stderr.replaceAll('\\','/')})`:cell(r.observed??r.reason??r.note);
    lines.push(`| ${cell(r.id)} | ${cell(r.expected??'not executed')} | ${r.status} | ${cell(r.exit)} | ${cell(command)} | ${cell(r.cwd)} | ${links} |`);
  }
  fs.writeFileSync(path.join(here,filename),lines.join('\n')+'\n');
}
