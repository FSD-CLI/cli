#!/usr/bin/env node
// docs/qa/2.6.1/evidence/scripts/qa-matrix.mjs
//
// Renders the matrix for a validation run from its raw results, so the committed matrix can be
// regenerated and checked against results.jsonl. No dependencies.
//
//   node docs/qa/2.6.1/evidence/scripts/qa-matrix.mjs [--in <validation dir>] [--out <markdown file>]
//
// Defaults: --in docs/qa/2.6.1/evidence/validation-r2, --out docs/qa/2.6.1/CLI-QA-MATRIX-r2.md
// Links in the output are relative to the folder that contains the output file.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const QA_DIR = path.resolve(HERE, "..", "..");
const argv = process.argv.slice(2);
const opt = (name, fallback) => {
  const i = argv.indexOf(`--${name}`);
  return i === -1 ? fallback : argv[i + 1];
};
const IN = path.resolve(opt("in", path.join(QA_DIR, "evidence", "validation-r2")));
const OUT = path.resolve(opt("out", path.join(QA_DIR, "CLI-QA-MATRIX-r2.md")));

const manifest = JSON.parse(fs.readFileSync(path.join(IN, "manifest.json"), "utf8"));
const rows = fs.readFileSync(path.join(IN, "results.jsonl"), "utf8").split("\n").filter(Boolean).map((l) => JSON.parse(l));

const relDir = path.relative(path.dirname(OUT), IN).split(path.sep).join("/");
const cell = (s) => String(s ?? "-").replace(/\|/g, "/").replace(/\r?\n/g, " ");
const link = (label, file) => `[${label}](${relDir}/${file.replaceAll("\\", "/")})`;

const count = (s) => rows.filter((r) => r.status === s).length;
const executed = count("PASS") + count("FAIL");
const groups = [...new Set(rows.map((r) => r.group))];
const dur = (r) => (r.durationMs === undefined ? "-" : r.durationMs < 1000 ? `${r.durationMs} ms` : `${(r.durationMs / 1000).toFixed(1)} s`);

const lines = [];
lines.push("# CLI QA Matrix, validation run r2 (generated)", "");
lines.push("Generated by `evidence/scripts/qa-matrix.mjs` from `results.jsonl`. Do not edit by hand; regenerate instead.", "");
lines.push("| Field | Value |", "|---|---|");
lines.push(`| Run started | ${manifest.createdAt} |`);
lines.push(`| Repository HEAD of the checkout that ran the script | \`${manifest.repoHead}\` (branch ${manifest.branch}) |`);
lines.push(`| Audited CLI SHA | \`${manifest.auditedCliSha}\` (version ${manifest.cliVersion}) |`);
lines.push(`| Script revision (SHA-256 of qa-evidence.mjs) | \`${manifest.scriptSha256}\` |`);
lines.push(`| Platform | ${manifest.os}, Node ${manifest.node} |`);
lines.push(`| Tools | ${Object.entries(manifest.tools).map(([k, v]) => `${k} ${v ?? "not installed"}`).join(", ")} |`);
lines.push(`| Repository root / workspace used | \`${manifest.repoRoot}\` / \`${manifest.workspace}\` |`);
lines.push(`| Groups run | ${manifest.groups.join(", ")} |`, "");
lines.push("## Counts", "");
lines.push("| Measure | Value |", "|---|---|");
lines.push(`| Rows | ${rows.length} |`, `| Executed (PASS + FAIL) | ${executed} |`, `| PASS | ${count("PASS")} |`, `| FAIL | ${count("FAIL")} |`);
lines.push(`| NOT TESTED | ${count("NOT TESTED")} |`, `| INFO (observations, not counted) | ${count("INFO")} |`);
lines.push(`| Coverage within this script's scope (executed / executed + NOT TESTED) | ${executed}/${executed + count("NOT TESTED")} |`);
lines.push(`| Pass rate (PASS / executed) | ${count("PASS")}/${executed} = ${executed ? ((100 * count("PASS")) / executed).toFixed(1) : "n/a"}% |`, "");
lines.push("The coverage figure above only covers what this script plans to run. It is not the coverage of the whole QA scope; see the report.", "");
lines.push("| Group | PASS | FAIL | NOT TESTED | INFO |", "|---|---|---|---|---|");
for (const g of groups) {
  const c = (s) => rows.filter((r) => r.group === g && r.status === s).length;
  lines.push(`| ${g} | ${c("PASS")} | ${c("FAIL")} | ${c("NOT TESTED")} | ${c("INFO")} |`);
}
lines.push("", "## Rows", "");
lines.push("| Case ID | Group | Command | Working directory | Exit | Duration | Expected | Status | Evidence | Note |", "|---|---|---|---|---|---|---|---|---|---|");
for (const r of rows) {
  const evidence = r.stdout ? `${link("stdout", r.stdout)} ${link("stderr", r.stderr)}` : "(assertion or observation; see note)";
  const exit = r.exit === undefined ? "-" : r.exit === null ? `none (${r.signal ?? r.spawnError ?? "no status"})` : r.exit;
  lines.push(`| ${cell(r.id)} | ${cell(r.group)} | ${r.command?.startsWith("(") ? cell(r.command) : "`" + cell(r.command) + "`"} | ${r.cwd ? "`" + cell(r.cwd) + "`" : "-"} | ${exit} | ${dur(r)} | ${cell(r.expected)} | **${r.status}** | ${evidence} | ${cell(r.note)} |`);
}
fs.writeFileSync(OUT, lines.join("\n") + "\n");
console.log(`Wrote ${OUT} (${rows.length} rows)`);
