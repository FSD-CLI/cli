import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

// Policy as Code (INT-35): the `fsd.policy.ts` format and its loader.
//
// This module only defines the format and loads + validates a policy file.
// It does NOT evaluate the project against the rules — that is INT-36
// (`fsd check` will enforce the loaded policy there). The format below is a
// proposal: it is deliberately minimal and may change before evaluation
// lands, so keep new rule ids behind this module instead of spreading
// policy knowledge across commands.
//
// INT-37 adds per-layer/per-slice `owners` and CODEOWNERS generation
// (`renderCodeowners` / `writeCodeowners`); INT-38 adds built-in presets
// (`POLICY_PRESETS`, applied with the `preset` field or scaffolded with
// `fsd policy --preset <name>`). Presets only set rule severities and
// default `allow` lists — they do not add a rule engine.

export const POLICY_VERSION = 1;

export const POLICY_FILE_NAMES = [
  "fsd.policy.ts",
  "fsd.policy.mjs",
  "fsd.policy.js",
];

// The canonical file is `fsd.policy.ts`. The `.mjs`/`.js` spellings exist
// because Node only strips types from `.ts` files by default on Node
// >= 22.18; on the CLI's minimum runtime (Node 22.12) a plain JavaScript
// policy file is the portable alternative.
export const POLICY_FILE_NAME = "fsd.policy.ts";

export const POLICY_LAYERS = [
  "app",
  "pages",
  "widgets",
  "features",
  "entities",
  "shared",
];

export const POLICY_SEVERITIES = ["error", "warn"];

// Rule ids proposed for format version 1. `layer-boundaries` restricts
// which layers a layer may import from; `no-slice-cross-imports` forbids
// slices in the same layer from importing each other;
// `no-public-api-bypass` requires imports to go through a slice's public
// API instead of reaching into its internals.
export const POLICY_RULE_IDS = [
  "layer-boundaries",
  "no-slice-cross-imports",
  "no-public-api-bypass",
];

const TOP_LEVEL_KEYS = new Set(["version", "rules", "owners", "preset"]);
const RULE_KEYS = new Set(["id", "severity", "allow"]);

// Built-in policy presets (INT-38). A preset is plain data: rule severities
// plus the default `allow` list for `layer-boundaries` — nothing else, no
// new rule engine. `recommended` is the standard FSD import order with
// public-API bypasses as warnings; `strict` turns every rule into an error
// and additionally forbids widgets from importing features (widgets compose
// entities and shared code only).
export const POLICY_PRESET_NAMES = ["recommended", "strict"];

export const POLICY_PRESETS = {
  recommended: {
    rules: [
      {
        id: "layer-boundaries",
        severity: "error",
        allow: {
          app: ["pages", "widgets", "features", "entities", "shared"],
          pages: ["widgets", "features", "entities", "shared"],
          widgets: ["features", "entities", "shared"],
          features: ["entities", "shared"],
          entities: ["shared"],
          shared: [],
        },
      },
      { id: "no-slice-cross-imports", severity: "error" },
      { id: "no-public-api-bypass", severity: "warn" },
    ],
  },
  strict: {
    rules: [
      {
        id: "layer-boundaries",
        severity: "error",
        allow: {
          app: ["pages", "widgets", "features", "entities", "shared"],
          pages: ["widgets", "features", "entities", "shared"],
          widgets: ["entities", "shared"],
          features: ["entities", "shared"],
          entities: ["shared"],
          shared: [],
        },
      },
      { id: "no-slice-cross-imports", severity: "error" },
      { id: "no-public-api-bypass", severity: "error" },
    ],
  },
};

// CODEOWNERS generation (INT-37). Generated files carry a header marker so
// `writeCodeowners` can tell a file it owns from one a human wrote.
export const CODEOWNERS_PATH = ".github/CODEOWNERS";
export const CODEOWNERS_HEADER =
  "# Generated by `fsd policy codeowners` from fsd.policy.ts — do not edit by hand.";

const OWNER_HANDLE_PATTERN =
  /^@[A-Za-z0-9](?:[A-Za-z0-9-]*[A-Za-z0-9])?(?:\/[A-Za-z0-9](?:[A-Za-z0-9-]*[A-Za-z0-9])?)?$/;
const OWNER_EMAIL_PATTERN = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
const SLICE_NAME_PATTERN = /^[a-z0-9][a-z0-9-]*$/;

export function isValidOwner(value) {
  return (
    typeof value === "string" &&
    (OWNER_HANDLE_PATTERN.test(value) || OWNER_EMAIL_PATTERN.test(value))
  );
}

// Apply a policy's `preset` field: preset rules fill in any rule the policy
// does not declare, and a declared rule overrides the preset rule with the
// same id field by field (an explicit severity or `allow` wins, the preset
// supplies the rest). Returns the policy unchanged when it declares no
// preset, or an unknown one (validation rejects unknown presets).
export function resolvePolicyPreset(policy) {
  if (!isPlainObject(policy) || typeof policy.preset !== "string") {
    return policy;
  }
  const preset = POLICY_PRESETS[policy.preset];
  if (!preset) return policy;
  const explicitById = new Map(
    (Array.isArray(policy.rules) ? policy.rules : [])
      .filter((rule) => isPlainObject(rule) && typeof rule.id === "string")
      .map((rule) => [rule.id, rule]),
  );
  const rules = preset.rules.map((presetRule) => {
    const explicit = explicitById.get(presetRule.id);
    return explicit ? { ...presetRule, ...explicit } : { ...presetRule };
  });
  for (const rule of explicitById.values()) {
    if (!preset.rules.some((presetRule) => presetRule.id === rule.id)) {
      rules.push({ ...rule });
    }
  }
  return { ...policy, rules };
}

// Map an `owners` key to the path it owns: a bare layer owns the whole
// layer directory, `layer/slice` owns that slice directory.
export function ownerKeyToPath(key) {
  const [layer, slice] = key.split("/");
  return slice ? `src/${layer}/${slice}/` : `src/${layer}/`;
}

// Render a CODEOWNERS file from a policy's `owners` map. Entries are
// ordered by layer (app → shared) with a bare layer before its slices, then
// alphabetically by slice. Returns null when the policy declares no owners.
export function renderCodeowners(policy) {
  if (!isPlainObject(policy) || !isPlainObject(policy.owners)) return null;
  const entries = Object.entries(policy.owners);
  if (entries.length === 0) return null;
  entries.sort(([aKey], [bKey]) => {
    const [aLayer, aSlice] = aKey.split("/");
    const [bLayer, bSlice] = bKey.split("/");
    const layerOrder =
      POLICY_LAYERS.indexOf(aLayer) - POLICY_LAYERS.indexOf(bLayer);
    if (layerOrder !== 0) return layerOrder;
    if (aSlice === undefined && bSlice !== undefined) return -1;
    if (aSlice !== undefined && bSlice === undefined) return 1;
    return (aSlice ?? "").localeCompare(bSlice ?? "");
  });
  const lines = [CODEOWNERS_HEADER, "# Regenerate with: fsd policy codeowners", ""];
  for (const [key, owners] of entries) {
    const ownerList = Array.isArray(owners) ? owners : [owners];
    lines.push(`${ownerKeyToPath(key)} ${ownerList.join(" ")}`);
  }
  return `${lines.join("\n")}\n`;
}

export function isGeneratedCodeowners(content) {
  return typeof content === "string" && content.includes(CODEOWNERS_HEADER);
}

// Scaffold a starter policy file from a preset (INT-38). Writes
// `fsd.policy.mjs` — the portable spelling on Node 22.12+ — declaring the
// preset with an empty `rules` list, so the preset supplies every rule and
// later edits override individual rules. Refuses to overwrite an existing
// policy file unless `force` is passed. Returns
// `{ path, status, reason? }` with status "created" or "refused".
export function scaffoldPolicy(cwd, preset, { force = false } = {}) {
  const file = path.join(cwd, POLICY_FILE_NAME.replace(/\.ts$/, ".mjs"));
  const existing = findPolicyFile(cwd);
  if (existing && !force) {
    return {
      path: existing,
      status: "refused",
      reason: `A policy file already exists (${path.basename(existing)}) — pass --force to replace it.`,
    };
  }
  const target = existing && force ? existing : file;
  const content = `// Policy as Code — see docs/POLICY-FORMAT.md.
// \`preset: "${preset}"\` applies the built-in ${preset} rules; declare
// \`rules\` below to override individual rules, or \`owners\` to map layers
// and slices to their owners (see \`fsd policy codeowners\`).
export default {
  version: 1,
  preset: "${preset}",
  rules: [],
};
`;
  fs.writeFileSync(target, content);
  return { path: target, status: "created" };
}

// Write CODEOWNERS from a policy. Never overwrites a hand-written file
// silently: when `.github/CODEOWNERS` exists and was not generated by us,
// the write is refused unless `force` is passed. Returns
// `{ path, status, reason? }` with status "created", "updated" or
// "refused".
export function writeCodeowners(cwd, policy, { force = false } = {}) {
  const content = renderCodeowners(policy);
  if (content === null) {
    return {
      path: path.join(cwd, CODEOWNERS_PATH),
      status: "refused",
      reason: "The policy declares no owners.",
    };
  }
  const file = path.join(cwd, CODEOWNERS_PATH);
  const existed = fs.existsSync(file);
  if (existed) {
    const existing = fs.readFileSync(file, "utf8");
    if (existing === content) {
      return { path: file, status: "updated" };
    }
    if (!isGeneratedCodeowners(existing) && !force) {
      return {
        path: file,
        status: "refused",
        reason:
          "CODEOWNERS already exists and was not generated by `fsd policy codeowners` — pass --force to replace it.",
      };
    }
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return { path: file, status: existed ? "updated" : "created" };
}

function isPlainObject(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

export function findPolicyFile(cwd = process.cwd()) {
  for (const fileName of POLICY_FILE_NAMES) {
    const candidate = path.join(cwd, fileName);
    if (fs.existsSync(candidate)) return candidate;
  }
  return null;
}

export function validatePolicy(policy) {
  const errors = [];
  if (!isPlainObject(policy)) {
    return ["Policy must export a default object."];
  }
  for (const key of Object.keys(policy)) {
    if (!TOP_LEVEL_KEYS.has(key)) {
      errors.push(`Unknown policy key "${key}".`);
    }
  }
  if (policy.version !== POLICY_VERSION) {
    errors.push(
      `Policy version must be ${POLICY_VERSION} (received ${JSON.stringify(policy.version)}).`,
    );
  }
  if (policy.preset !== undefined) {
    if (typeof policy.preset !== "string") {
      errors.push(
        `Policy "preset" must be a preset name (received ${JSON.stringify(policy.preset)}).`,
      );
    } else if (!POLICY_PRESET_NAMES.includes(policy.preset)) {
      errors.push(
        `Policy "preset": unknown preset "${policy.preset}" (supported: ${POLICY_PRESET_NAMES.join(", ")}).`,
      );
    }
  }
  if (policy.owners !== undefined) {
    if (!isPlainObject(policy.owners)) {
      errors.push(
        'Policy "owners" must map a layer or "layer/slice" to owner(s).',
      );
    } else {
      for (const [key, owners] of Object.entries(policy.owners)) {
        const parts = key.split("/");
        const [layer, slice] = parts;
        if (parts.length > 2 || !POLICY_LAYERS.includes(layer)) {
          errors.push(
            `Owners "${key}" must start with a layer (${POLICY_LAYERS.join(", ")}), optionally followed by "/slice".`,
          );
          continue;
        }
        if (slice !== undefined && !SLICE_NAME_PATTERN.test(slice)) {
          errors.push(
            `Owners "${key}": slice names use lowercase letters, digits and dashes (received "${slice}").`,
          );
          continue;
        }
        const ownerList = Array.isArray(owners) ? owners : [owners];
        if (
          ownerList.length === 0 ||
          ownerList.some((owner) => !isValidOwner(owner))
        ) {
          errors.push(
            `Owners "${key}" must be an owner handle ("@team" or "@org/team") or an email, or a non-empty list of them.`,
          );
        }
      }
    }
  }
  if (!Array.isArray(policy.rules)) {
    errors.push("Policy \"rules\" must be an array.");
    return errors;
  }
  const seenIds = new Set();
  policy.rules.forEach((rule, index) => {
    const where = `Rule ${index + 1}`;
    if (!isPlainObject(rule)) {
      errors.push(`${where} must be an object.`);
      return;
    }
    for (const key of Object.keys(rule)) {
      if (!RULE_KEYS.has(key)) {
        errors.push(`${where}: unknown key "${key}".`);
      }
    }
    if (typeof rule.id !== "string" || rule.id.length === 0) {
      errors.push(`${where} must have a string "id".`);
      return;
    }
    if (!POLICY_RULE_IDS.includes(rule.id)) {
      errors.push(
        `${where}: unknown rule id "${rule.id}" (supported: ${POLICY_RULE_IDS.join(", ")}).`,
      );
      return;
    }
    if (seenIds.has(rule.id)) {
      errors.push(`${where}: duplicate rule id "${rule.id}".`);
    }
    seenIds.add(rule.id);
    if (
      rule.severity !== undefined &&
      !POLICY_SEVERITIES.includes(rule.severity)
    ) {
      errors.push(
        `${where} ("${rule.id}"): severity must be ${POLICY_SEVERITIES.map((severity) => `"${severity}"`).join(" or ")} (received ${JSON.stringify(rule.severity)}).`,
      );
    }
    if (rule.id === "layer-boundaries" && rule.allow !== undefined) {
      if (!isPlainObject(rule.allow)) {
        errors.push(
          `${where} ("layer-boundaries"): "allow" must map a layer to the layers it may import.`,
        );
      } else {
        for (const [layer, allowed] of Object.entries(rule.allow)) {
          if (!POLICY_LAYERS.includes(layer)) {
            errors.push(
              `${where} ("layer-boundaries"): unknown layer "${layer}" in "allow" (layers: ${POLICY_LAYERS.join(", ")}).`,
            );
            continue;
          }
          if (
            !Array.isArray(allowed) ||
            allowed.some((entry) => !POLICY_LAYERS.includes(entry))
          ) {
            errors.push(
              `${where} ("layer-boundaries"): "${layer}" may only allow layers (${POLICY_LAYERS.join(", ")}).`,
            );
            continue;
          }
          if (allowed.includes(layer)) {
            errors.push(
              `${where} ("layer-boundaries"): "${layer}" cannot allow itself.`,
            );
          }
        }
      }
    }
    if (rule.id !== "layer-boundaries" && rule.allow !== undefined) {
      errors.push(
        `${where} ("${rule.id}"): "allow" only applies to "layer-boundaries".`,
      );
    }
  });
  return errors;
}

export async function loadPolicy(cwd = process.cwd()) {
  const file = findPolicyFile(cwd);
  if (!file) {
    return { found: false, path: null, policy: null, errors: [] };
  }
  let module;
  try {
    module = await import(pathToFileURL(file).href);
  } catch (error) {
    const hint =
      file.endsWith(".ts") && process.features.typescript !== "strip"
        ? " Loading a .ts policy needs Node >= 22.18 (type stripping) — use fsd.policy.mjs instead, or upgrade Node."
        : "";
    return {
      found: true,
      path: file,
      policy: null,
      errors: [`Failed to load ${path.basename(file)}: ${error.message}.${hint}`],
    };
  }
  const policy = module.default;
  if (policy === undefined) {
    return {
      found: true,
      path: file,
      policy: null,
      errors: [
        `${path.basename(file)} must have a default export (see docs/POLICY-FORMAT.md).`,
      ],
    };
  }
  const errors = validatePolicy(policy);
  // A valid policy with a `preset` is returned with the preset applied, so
  // consumers (and `fsd policy`) see the effective rules. When validation
  // fails the raw policy is returned untouched, with the errors.
  return {
    found: true,
    path: file,
    policy: errors.length === 0 ? resolvePolicyPreset(policy) : policy,
    errors,
  };
}
