import path from "node:path";
import chalk from "chalk";
import {
  POLICY_FILE_NAMES,
  loadPolicy,
  renderCodeowners,
  scaffoldPolicy,
  writeCodeowners,
} from "../core/policy.mjs";

// `fsd policy` loads and validates the project's policy file
// (fsd.policy.ts, or fsd.policy.mjs / fsd.policy.js). It reports what the
// policy declares; it does not evaluate the project against the rules —
// that is INT-36. Exit code 1 when the file exists but is invalid.
//
// `fsd policy --preset <name>` (INT-38) scaffolds a starter policy file
// from a built-in preset instead of reporting; it refuses to overwrite an
// existing policy file unless `--force` is passed.
//
// `fsd policy codeowners [--force]` (INT-37) generates `.github/CODEOWNERS`
// from the policy's `owners` map. It never overwrites a hand-written
// CODEOWNERS silently: an existing file that was not generated by this
// command is refused unless `--force` is passed.
export async function runPolicyProject(command, cwd = process.cwd()) {
  if (command.preset) {
    const { path: file, status, reason } = scaffoldPolicy(cwd, command.preset, {
      force: command.force,
    });
    if (status === "refused") {
      throw new Error(reason);
    }
    console.log(chalk.bold("\n  FSD policy\n"));
    console.log(`  Created ${path.relative(cwd, file) || file} from the "${command.preset}" preset.`);
    console.log(
      "  Edit `rules` to override individual rules, or add `owners` to map layers and slices to their owners.\n",
    );
    return;
  }

  const { found, path: file, policy, errors } = await loadPolicy(cwd);
  if (!found) {
    console.log(chalk.bold("\n  FSD policy\n"));
    console.log(
      `  No policy file found (looked for ${POLICY_FILE_NAMES.join(", ")}).`,
    );
    console.log(
      "  Create fsd.policy.ts to declare project rules — see docs/POLICY-FORMAT.md.",
    );
    console.log(
      "  Or scaffold one from a preset: fsd policy --preset recommended\n",
    );
    return;
  }

  if (errors.length) {
    throw new Error(
      `Invalid policy in ${path.basename(file)}:\n${errors.map((error) => `  - ${error}`).join("\n")}`,
    );
  }

  if (command.subcommand === "codeowners") {
    const content = renderCodeowners(policy);
    if (content === null) {
      throw new Error(
        "The policy declares no owners — add an `owners` map to fsd.policy.ts first (see docs/POLICY-FORMAT.md).",
      );
    }
    const { path: outFile, status, reason } = writeCodeowners(cwd, policy, {
      force: command.force,
    });
    if (status === "refused") {
      throw new Error(reason);
    }
    console.log(chalk.bold("\n  FSD policy\n"));
    console.log(
      `  ${status === "created" ? "Created" : "Updated"} ${path.relative(cwd, outFile) || outFile} from ${path.basename(file)}.`,
    );
    console.log(
      "  Regenerate after changing `owners` with: fsd policy codeowners\n",
    );
    return;
  }

  console.log(chalk.bold("\n  FSD policy\n"));
  console.log(`  File: ${path.relative(cwd, file) || file}`);
  console.log(`  Version: ${policy.version}`);
  if (policy.preset) {
    console.log(`  Preset: ${policy.preset}`);
  }
  console.log(`  Rules: ${policy.rules.length}`);
  for (const rule of policy.rules) {
    const severity = rule.severity ?? "error";
    const detail =
      rule.id === "layer-boundaries" && rule.allow
        ? ` — ${Object.entries(rule.allow)
            .map(([layer, allowed]) => `${layer} → ${allowed.join(", ") || "none"}`)
            .join("; ")}`
        : "";
    console.log(`  - ${rule.id} (${severity})${detail}`);
  }
  if (policy.owners) {
    const ownerEntries = Object.entries(policy.owners);
    console.log(`  Owners: ${ownerEntries.length}`);
    for (const [key, owners] of ownerEntries) {
      const ownerList = Array.isArray(owners) ? owners : [owners];
      console.log(`  - ${key}: ${ownerList.join(", ")}`);
    }
  }
  console.log(
    "\n  Rules are declared here but not evaluated yet — enforcement lands with fsd check (INT-36).\n",
  );
}
