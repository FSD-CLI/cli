import fs from "node:fs";
import path from "node:path";
import chalk from "chalk";
import { explainProject } from "./explain-project.mjs";

export const AGENTS_FILE = "AGENTS.md";
export const CURSOR_RULES_FILE = path.join(".cursor", "rules", "fsd-cli.mdc");

function renderStackSection(config) {
  return [
    "## Stack",
    "",
    `- Framework: ${config.framework}`,
    `- Package manager: ${config.packageManager}`,
    `- API client: ${config.apiClient}`,
    `- Server state: ${config.serverState}`,
    `- Client state: ${config.clientState}`,
    `- Forms: ${config.forms}`,
    "",
  ];
}

function renderLayersSection(sourceRoot, layers, total) {
  const lines = [
    "## Architecture — Feature-Sliced Design",
    "",
    `Layers live under \`${path.relative(process.cwd(), sourceRoot) || sourceRoot}/\`, highest to lowest:`,
    "",
  ];
  for (const { layer, slices, kind } of layers) {
    const noun = slices.length === 1 ? kind : `${kind}s`;
    const names = slices.length ? `: ${slices.join(", ")}` : "";
    lines.push(`- ${layer} — ${slices.length} ${noun}${names}`);
  }
  lines.push("", `Total slices: ${total}`, "");
  return lines;
}

function renderRulesSection() {
  return [
    "## Rules",
    "",
    "- Imports flow downward only: app → pages → widgets → features → entities → shared. Never import from a higher layer, and never import across slices in the same layer.",
    "- Each slice exposes its public API through its own `index.ts` (or `index.js`); import a slice only through that public API, never through its internal files.",
    "- `shared` holds reusable, framework-agnostic code only — no business logic and no imports from any other layer.",
    "- `app` wires the application together (providers, routing, global styles); it holds no business logic.",
    "- `pages` compose widgets and features into routes; `widgets` compose features and entities; `features` implement user actions; `entities` hold business data and its UI.",
    "- Add a slice with `npx create-fsd-architecture generate <layer> <name>`; never hand-create layer folders.",
    "",
  ];
}

function renderCommandsSection() {
  return [
    "## Common commands",
    "",
    "- `npx create-fsd-architecture --generate feature <name>` — generate a slice",
    "- `npx create-fsd-architecture check` — inspect config and layers",
    "- `npx create-fsd-architecture doctor` — diagnose the project and toolchain",
    "- `npx create-fsd-architecture config` — print the resolved configuration",
    "- `npx create-fsd-architecture explain` — print the project summary",
    "- `npx create-fsd-architecture history` — sample recent commits by FSD layer",
    "- `npx create-fsd-architecture agent-rules` — regenerate this file",
    "",
  ];
}

export function renderAgentsMd(report) {
  const { config, sourceRoot, layers, total } = report;
  return [
    "# AGENTS.md",
    "",
    "> Generated by `fsd agent-rules` from this project's FSD CLI configuration.",
    "> Regenerate with `npx create-fsd-architecture agent-rules --force` after",
    "> changing the stack or adding slices; hand edits are lost on regeneration.",
    "",
    ...renderStackSection(config),
    ...renderLayersSection(sourceRoot, layers, total),
    ...renderRulesSection(),
    ...renderCommandsSection(),
  ].join("\n");
}

export function renderCursorRules(report) {
  const { config, sourceRoot, layers, total } = report;
  return [
    "---",
    "description: Feature-Sliced Design rules for this project (generated by fsd agent-rules)",
    "globs: src/**/*, app/**/*",
    "alwaysApply: false",
    "---",
    "",
    "# FSD CLI rules",
    "",
    `This project uses Feature-Sliced Design, scaffolded with FSD CLI (\`create-fsd-architecture\`). Framework: ${config.framework}; package manager: ${config.packageManager}.`,
    "",
    ...renderLayersSection(sourceRoot, layers, total),
    ...renderRulesSection(),
  ].join("\n");
}

export async function runAgentRules(
  command,
  cwd = process.cwd(),
  { force = false } = {},
) {
  const report = explainProject(cwd);
  const agentsPath = path.join(cwd, AGENTS_FILE);
  const cursorPath = path.join(cwd, CURSOR_RULES_FILE);

  const existing = [agentsPath, cursorPath].filter((file) =>
    fs.existsSync(file),
  );
  if (existing.length && !force) {
    const names = existing
      .map((file) => path.relative(cwd, file))
      .join(" and ");
    throw new Error(
      `${names} already exist${
        existing.length > 1 ? "" : "s"
      }. Use --force to replace ${existing.length > 1 ? "them" : "it"}.`,
    );
  }

  fs.writeFileSync(agentsPath, renderAgentsMd(report), "utf8");
  fs.mkdirSync(path.dirname(cursorPath), { recursive: true });
  fs.writeFileSync(cursorPath, renderCursorRules(report), "utf8");
  console.log(`  Wrote ${path.relative(cwd, agentsPath)}`);
  console.log(`  Wrote ${path.relative(cwd, cursorPath)}`);
  console.log(chalk.dim("  Regenerate with: fsd agent-rules --force"));
}
