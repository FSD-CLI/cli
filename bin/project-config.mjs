function toTypeScriptLiteral(value, depth = 0) {
  if (Array.isArray(value)) {
    return `[${value.map((item) => toTypeScriptLiteral(item, depth)).join(", ")}]`;
  }

  if (value && typeof value === "object") {
    const indentation = "  ".repeat(depth);
    const propertyIndentation = "  ".repeat(depth + 1);
    const properties = Object.entries(value).map(([key, item]) => {
      const property = /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
      return `${propertyIndentation}${property}: ${toTypeScriptLiteral(item, depth + 1)},`;
    });
    return `{\n${properties.join("\n")}\n${indentation}}`;
  }

  return JSON.stringify(value);
}

function configurePackageManager(targetDir, packageManager, framework) {
  if (packageManager === "pnpm") {
    const workspacePath = path.join(targetDir, "pnpm-workspace.yaml");
    // pnpm >=10.26 and 11 use allowBuilds. Do not replace a template-owned
    // workspace or approval policy, and never approve arbitrary dependencies.
    if (!fs.existsSync(workspacePath)) {
      const buildDependencies = {
        "react-vite": ["@swc/core", "esbuild"],
        nextjs: ["sharp", "unrs-resolver"],
        "vue-vite": ["esbuild", "vue-demi"],
        nuxt: ["esbuild", "unrs-resolver", "vue-demi"],
        sveltekit: ["esbuild"],
      }[framework];
      fs.writeFileSync(workspacePath, [
        "# pnpm >=10.26: only these framework build dependencies may run scripts.",
        "# Review new dependencies explicitly with pnpm approve-builds.",
        "strictDepBuilds: true",
        "allowBuilds:",
        ...buildDependencies.map((name) => `  ${JSON.stringify(name)}: true`),
        "",
      ].join("\n"));
    }
  }
  const yarnConfigPath = path.join(targetDir, ".yarnrc.yml");
  if (packageManager === "yarn") {
    fs.writeFileSync(yarnConfigPath, "nodeLinker: node-modules\n");
    const yarnLockPath = path.join(targetDir, "yarn.lock");
    if (!fs.existsSync(yarnLockPath)) fs.writeFileSync(yarnLockPath, "");
    return;
  }

  if (fs.existsSync(yarnConfigPath)) fs.rmSync(yarnConfigPath);
}

function removeForeignLockfiles(targetDir, packageManager) {
  const lockfiles = getLockfiles(packageManager);
  const keep = new Set(lockfiles.keep);

  for (const name of lockfiles.all) {
    const lockPath = path.join(targetDir, name);
    if (!keep.has(name) && fs.existsSync(lockPath)) {
      fs.rmSync(lockPath);
    }
  }
}

function updateDependencies(targetDir, config) {
  const adapter = getFrameworkAdapter(config.framework);
  const packagePath = path.join(targetDir, "package.json");
  const packageJson = JSON.parse(fs.readFileSync(packagePath, "utf8"));
  packageJson.dependencies ??= {};

  for (const name of listManagedDependencies()) {
    delete packageJson.dependencies[name];
    delete packageJson.devDependencies?.[name];
  }

  const selected = ["apiClient", "serverState", "clientState", "forms"].flatMap(
    (capability) => adapter.dependencies[capability]?.[config[capability]] ?? []
  );

  selected.push(...(adapter.baseDependencies ?? []));

  for (const name of selected) {
    packageJson.dependencies[name] = adapter.dependencyVersions[name];
  }

  packageJson.dependencies = sortObject(packageJson.dependencies);
  if (packageJson.devDependencies) {
    packageJson.devDependencies = sortObject(packageJson.devDependencies);
  }

  writeJson(packagePath, packageJson);
}

function writeApiClient(targetDir, config) {
  const adapter = getFrameworkAdapter(config.framework);
  const apiDir = path.join(targetDir, adapter.sourceDirectory, "shared", "api");
  fs.mkdirSync(apiDir, { recursive: true });
  fs.writeFileSync(
    path.join(apiDir, "client.ts"),
    adapter.runtime === "nuxt"
      ? config.apiClient === "axios"
        ? nuxtAxiosClientContent()
        : nuxtFetchClientContent()
      : adapter.runtime === "sveltekit"
      ? config.apiClient === "axios"
        ? sveltekitAxiosClientContent(adapter)
        : sveltekitFetchClientContent(adapter)
      : config.apiClient === "axios"
      ? axiosClientContent(adapter)
      : fetchClientContent(adapter)
  );
  fs.writeFileSync(
    path.join(apiDir, "index.ts"),
    'export { apiClient } from "./client";\n'
  );
}

function writeProviders(targetDir, config) {
  const adapter = getFrameworkAdapter(config.framework);
  if (adapter.runtime === "nuxt") {
    writeNuxtProviders(targetDir, config);
    return;
  }
  if (adapter.runtime === "sveltekit") {
    writeSvelteKitProviders(targetDir, config);
    return;
  }
  if (adapter.family === "vue") {
    writeVueProviders(targetDir, config);
    return;
  }

  writeReactProviders(targetDir, config);
}

function writeNuxtProviders(targetDir, config) {
  const nuxtConfigPath = path.join(targetDir, "nuxt.config.ts");
  if (!fs.existsSync(nuxtConfigPath)) {
    throw new Error("Nuxt template is missing nuxt.config.ts.");
  }

  const selectedModules = [];
  if (config.clientState === "pinia") selectedModules.push("'@pinia/nuxt',");
  if (config.forms === "vee-validate-zod") {
    selectedModules.push("'@vee-validate/nuxt',");
  }
  replaceMarkerBlock(
    nuxtConfigPath,
    "// fsd-cli:modules:start",
    "// fsd-cli:modules:end",
    selectedModules
  );

  const pluginPath = path.join(targetDir, "app", "plugins", "vue-query.ts");
  if (config.serverState === "vue-query") {
    fs.mkdirSync(path.dirname(pluginPath), { recursive: true });
    fs.writeFileSync(pluginPath, nuxtVueQueryPluginContent());
  } else if (fs.existsSync(pluginPath)) {
    fs.rmSync(pluginPath);
  }
}

